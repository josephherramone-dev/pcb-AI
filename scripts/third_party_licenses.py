#!/usr/bin/env python3
"""List the licenses of runtime dependencies (Python backend + npm frontend).

Usage (from the repository root, after installing both projects):
    backend/.venv/bin/python scripts/third_party_licenses.py > docs/legal/DEPENDENCY_LICENSES.md

Reads installed package metadata only; it does not contact the network.
Licenses are reported as declared by each package; review anything marked
"UNKNOWN" or copyleft by hand.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COPYLEFT = re.compile(r"\b(A?GPL|LGPL|MPL|EPL|CDDL|CC-BY-SA)", re.I)


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def python_runtime() -> list[tuple[str, str, str]]:
    """Transitive runtime requirements of the backend package."""
    seen: dict[str, tuple[str, str, str]] = {}
    queue = ["pcbai-backend"]
    while queue:
        name = queue.pop()
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        key = _norm(dist.metadata["Name"])
        if key in seen:
            continue
        lic = dist.metadata.get("License-Expression") or ""
        if not lic or len(lic) > 60:
            classifiers = [c.split("::")[-1].strip() for c in dist.metadata.get_all("Classifier") or []
                           if c.startswith("License ::")]
            raw = (dist.metadata.get("License") or "").strip().splitlines()
            lic = ", ".join(classifiers) or (raw[0][:60] if raw else "") or "UNKNOWN"
        if key != "pcbai-backend":
            seen[key] = (dist.metadata["Name"], dist.version, lic)
        for req in dist.requires or []:
            if "extra ==" in req and "extra == \"standard\"" not in req and "extra == \"redis\"" not in req \
                    and "extra == \"binary\"" not in req:
                continue
            queue.append(re.split(r"[ ;<>=!~\[(]", req, maxsplit=1)[0])
    return sorted(seen.values(), key=lambda r: r[0].lower())


def npm_runtime() -> list[tuple[str, str, str]]:
    fe = ROOT / "frontend"
    out = subprocess.run(["npm", "ls", "--omit=dev", "--all", "--json"], cwd=fe, capture_output=True, text=True)
    tree = json.loads(out.stdout or "{}")
    rows: dict[str, tuple[str, str, str]] = {}

    def walk(deps: dict) -> None:
        for name, info in (deps or {}).items():
            ver = info.get("version", "")
            if not ver or info.get("missing"):
                continue  # optional/peer dependency not installed (e.g. binaries for other platforms)
            if f"{name}@{ver}" not in rows:
                pkg = fe / "node_modules" / name / "package.json"
                lic = "UNKNOWN"
                if pkg.is_file():
                    data = json.loads(pkg.read_text())
                    lic = data.get("license") or "UNKNOWN"
                    if isinstance(lic, dict):
                        lic = lic.get("type", "UNKNOWN")
                rows[f"{name}@{ver}"] = (name, ver, str(lic))
            walk(info.get("dependencies"))

    walk(tree.get("dependencies"))
    return sorted(rows.values(), key=lambda r: r[0].lower())


def table(rows: list[tuple[str, str, str]]) -> str:
    lines = ["| Package | Version | License |", "|---|---|---|"]
    for name, ver, lic in rows:
        flag = " ⚠" if COPYLEFT.search(lic) or lic == "UNKNOWN" else ""
        lines.append(f"| {name} | {ver} | {lic}{flag} |")
    return "\n".join(lines)


def main() -> int:
    py = python_runtime()
    js = npm_runtime()
    print("# Runtime dependency licenses\n")
    print("Generated by `scripts/third_party_licenses.py` from installed package metadata. "
          "⚠ marks copyleft or undeclared licenses that need a manual review.\n")
    print(f"## Backend (Python) — {len(py)} packages\n")
    print(table(py))
    print(f"\n## Frontend (npm, production) — {len(js)} packages\n")
    print(table(js))
    return 0


if __name__ == "__main__":
    sys.exit(main())
