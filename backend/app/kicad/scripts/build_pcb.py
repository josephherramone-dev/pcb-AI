"""Build a native .kicad_pcb with KiCad's own Python API (pcbnew).

Runs inside the KiCad Python interpreter as an isolated subprocess:

    <kicad-python> build_pcb.py <spec.json>

Only the standard library and ``pcbnew`` are used. The spec is produced by the
backend from a validated design document; this script never evaluates code or
shell commands from its input. A JSON summary of what KiCad actually built is
printed on the last line of stdout.
"""

import json
import os
import sys

import pcbnew


def mm(v):
    return pcbnew.FromMM(float(v))


def vec(x, y):
    return pcbnew.VECTOR2I(mm(x), mm(y))


def set_width(item, w):
    try:
        item.SetWidth(mm(w))
    except TypeError:  # KiCad 9 padstack-aware signature
        item.SetWidth(mm(w), pcbnew.F_Cu)


def main(spec_path):
    with open(spec_path, encoding="utf-8") as fh:
        spec = json.load(fh)

    board = pcbnew.BOARD()
    board.SetCopperLayerCount(2)
    tb = board.GetTitleBlock()
    tb.SetTitle(spec.get("title", ""))
    tb.SetComment(0, "Generated by PCB AI from a validated design document")

    nets = {}
    for name in spec["nets"]:
        ni = pcbnew.NETINFO_ITEM(board, name)
        board.Add(ni)
        nets[name] = ni

    summary = {"kicad_version": pcbnew.Version(), "footprints": [], "missing_pads": []}
    fp_root = spec["footprint_dir"]
    for comp in spec["components"]:
        lib, name = comp["footprint"].split(":", 1)
        fp = pcbnew.FootprintLoad(os.path.join(fp_root, lib + ".pretty"), name)
        if fp is None:
            raise SystemExit(f"footprint {comp['footprint']} could not be loaded")
        fp.SetFPID(pcbnew.LIB_ID(lib, name))
        fp.SetReference(comp["ref"])
        fp.SetValue(comp["value"])
        if comp.get("symbol_uuid"):
            fp.SetPath(pcbnew.KIID_PATH("/" + comp["symbol_uuid"]))
        board.Add(fp)
        fp.SetPosition(vec(comp["x"], comp["y"]))
        fp.SetOrientationDegrees(float(comp.get("rotation", 0)))
        pad_numbers = set()
        for pad in fp.Pads():
            num = pad.GetNumber()
            pad_numbers.add(num)
            net = comp["pads"].get(num)
            if net:
                pad.SetNet(nets[net])
        for num in comp["pads"]:
            if num not in pad_numbers:
                summary["missing_pads"].append(f"{comp['ref']}.{num}")
        summary["footprints"].append({"ref": comp["ref"], "pads": sorted(pad_numbers)})

    pts = spec["outline"]
    for i, a in enumerate(pts):
        b = pts[(i + 1) % len(pts)]
        seg = pcbnew.PCB_SHAPE(board)
        seg.SetShape(pcbnew.SHAPE_T_SEGMENT)
        seg.SetStart(vec(*a))
        seg.SetEnd(vec(*b))
        seg.SetLayer(pcbnew.Edge_Cuts)
        set_width(seg, 0.1)
        board.Add(seg)

    layers = {"F.Cu": pcbnew.F_Cu, "B.Cu": pcbnew.B_Cu}
    for t in spec["tracks"]:
        tr = pcbnew.PCB_TRACK(board)
        tr.SetStart(vec(*t["start"]))
        tr.SetEnd(vec(*t["end"]))
        set_width(tr, t["width"])
        tr.SetLayer(layers[t["layer"]])
        tr.SetNet(nets[t["net"]])
        board.Add(tr)

    for v in spec["vias"]:
        via = pcbnew.PCB_VIA(board)
        via.SetPosition(vec(v["x"], v["y"]))
        set_width(via, v["diameter"])
        via.SetDrill(mm(v["drill"]))
        via.SetLayerPair(pcbnew.F_Cu, pcbnew.B_Cu)
        via.SetNet(nets[v["net"]])
        board.Add(via)

    out = spec["output"]
    if not pcbnew.SaveBoard(out, board):
        raise SystemExit("SaveBoard failed")

    # Re-load what was written to report KiCad's view of the file.
    loaded = pcbnew.LoadBoard(out)
    summary["loaded"] = {
        "footprints": len(loaded.GetFootprints()),
        "tracks": len(loaded.GetTracks()),
        "nets": loaded.GetNetCount(),
    }
    print(json.dumps(summary))


if __name__ == "__main__":
    main(sys.argv[1])
