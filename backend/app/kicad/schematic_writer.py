"""Generate native KiCad schematic files (``.kicad_sch``) from a design document.

Symbol definitions are copied from the installed KiCad libraries into the
schematic's ``lib_symbols`` section (as KiCad itself does), so the file is
self-contained. The S-expression dialect follows the version of the installed
symbol libraries so that the embedded definitions and the file header agree.
"""

from __future__ import annotations

import uuid

from app.design.model import DesignDocument
from app.kicad.schematic_layout import compute_layout, lib_to_sheet
from app.library import sexpr
from app.library.service import LibraryService
from app.library.sexpr import Sym

# Schematic file format versions written by KiCad releases.
SCH_VERSION_KICAD7 = 20230121
SCH_VERSION_KICAD8 = 20231120
SCH_VERSION_KICAD9 = 20250114

_NS = uuid.UUID("6f1d2c3e-6a55-4cf2-9a51-7b1f0f3c9d10")


def _uid(seed: str, *parts: str) -> str:
    return str(uuid.uuid5(_NS, ":".join((seed, *parts))))


def schematic_version_for_library(library: LibraryService) -> int:
    """Choose the schematic format version matching the installed symbol library."""
    lib_version = 0
    path = library.symbols.root / "Device.kicad_sym"
    try:
        with path.open(encoding="utf-8") as fh:
            head = fh.read(400)
        tree_head = head.split("(version", 1)[1].split(")", 1)[0]
        lib_version = int(tree_head.strip())
    except (OSError, IndexError, ValueError):
        pass
    if lib_version >= 20241209:
        return SCH_VERSION_KICAD9
    if lib_version >= 20231120:
        return SCH_VERSION_KICAD8
    return SCH_VERSION_KICAD7


def _n(v: float) -> Sym:
    return Sym(sexpr.fmt_num(v))


def _effects(hidden: bool = False, justify: list[str] | None = None, new_syntax: bool = False) -> list:
    eff: list = [Sym("effects"), [Sym("font"), [Sym("size"), _n(1.27), _n(1.27)]]]
    if justify:
        eff.append([Sym("justify"), *[Sym(j) for j in justify]])
    if hidden:
        eff.append([Sym("hide"), Sym("yes")] if new_syntax else Sym("hide"))
    return eff


def _yesno(flag: bool) -> Sym:
    return Sym("yes" if flag else "no")


def write_schematic(doc: DesignDocument, library: LibraryService, project_name: str, seed: str) -> str:
    version = schematic_version_for_library(library)
    new_syntax = version >= SCH_VERSION_KICAD8
    layout = compute_layout(doc, library)
    root_uuid = _uid(seed, "root")

    out: list = [
        Sym("kicad_sch"),
        [Sym("version"), Sym(str(version))],
        [Sym("generator"), "pcbai"],
    ]
    if new_syntax:
        out.append([Sym("generator_version"), "0.1"])
    out += [
        [Sym("uuid"), root_uuid],
        [Sym("paper"), "A4"],
        [Sym("title_block"), [Sym("title"), doc.title or project_name],
         [Sym("comment"), Sym("1"), "Generated by PCB AI from a validated design document"]],
    ]

    lib_symbols: list = [Sym("lib_symbols")]
    for lib_id in sorted(layout.symbols):
        lib_symbols.append(layout.symbols[lib_id].node)
    out.append(lib_symbols)

    for i, (x, y) in enumerate(layout.no_connects):
        out.append([Sym("no_connect"), [Sym("at"), _n(x), _n(y)], [Sym("uuid"), _uid(seed, "nc", str(i))]])

    for i, st in enumerate(layout.stubs):
        out.append([
            Sym("wire"),
            [Sym("pts"), [Sym("xy"), _n(st.x1), _n(st.y1)], [Sym("xy"), _n(st.x2), _n(st.y2)]],
            [Sym("stroke"), [Sym("width"), _n(0)], [Sym("type"), Sym("default")]],
            [Sym("uuid"), _uid(seed, "wire", str(i))],
        ])
        out.append([
            Sym("label"), st.net,
            [Sym("at"), _n(st.x2), _n(st.y2), _n(st.label_angle)],
            [Sym("fields_autoplaced"), Sym("yes")] if new_syntax else [Sym("fields_autoplaced")],
            _effects(justify=[st.label_justify, "bottom"]),
            [Sym("uuid"), _uid(seed, "label", str(i))],
        ])

    for comp in doc.components:
        symbol = layout.symbols[comp.lib_symbol]
        rot = comp.schematic.rotation
        node: list = [
            Sym("symbol"),
            [Sym("lib_id"), comp.lib_symbol],
            [Sym("at"), _n(comp.schematic.x), _n(comp.schematic.y), _n(rot)],
            [Sym("unit"), Sym("1")],
        ]
        if new_syntax:
            node.append([Sym("exclude_from_sim"), Sym("no")])
        node += [
            [Sym("in_bom"), _yesno(comp.in_bom)],
            [Sym("on_board"), _yesno(comp.on_board)],
            [Sym("dnp"), Sym("no")],
            [Sym("uuid"), _uid(seed, "sym", comp.ref)],
        ]
        lib_props = {str(p[1]): p for p in sexpr.children(symbol.node, "property")}
        fields = [
            ("Reference", comp.ref, False),
            ("Value", comp.value, False),
            ("Footprint", comp.footprint or "", True),
            ("Datasheet", symbol.properties.get("Datasheet", "~") or "~", True),
        ]
        if symbol.is_power:
            fields[0] = ("Reference", comp.ref, True)
        for name, val, hidden in fields:
            lp = lib_props.get(name)
            at = sexpr.child(lp, "at") if lp else None
            px, py = (sexpr.num(at, 1), sexpr.num(at, 2)) if at else (0.0, 0.0)
            pangle = sexpr.num(at, 3) if at else 0.0
            sx, sy = lib_to_sheet(comp, px, py)
            angle = (pangle + rot) % 180
            node.append([
                Sym("property"), name, val,
                [Sym("at"), _n(sx), _n(sy), _n(angle)],
                _effects(hidden=hidden or (lp is not None and sexpr.is_hidden(lp)), new_syntax=new_syntax),
            ])
        for pin in symbol.pins:
            if pin.unit in (0, 1):
                node.append([Sym("pin"), pin.number, [Sym("uuid"), _uid(seed, "pin", comp.ref, pin.number)]])
        node.append([
            Sym("instances"),
            [Sym("project"), project_name,
             [Sym("path"), f"/{root_uuid}", [Sym("reference"), comp.ref], [Sym("unit"), Sym("1")]]],
        ])
        out.append(node)

    out.append([Sym("sheet_instances"), [Sym("path"), "/", [Sym("page"), "1"]]])
    return sexpr.dumps(out) + "\n"
